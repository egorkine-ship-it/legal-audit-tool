def _replace_preserve_case(text: str, needle: str, replacement: str) -> str:
    """Регистронезависимая замена подстроки needle на replacement.

    Замена простая: ищем в нижнем регистре, заменяем в исходной строке.
    Не пытаемся сохранять исходный регистр слова — для нейтрального тона это
    не критично, но результат остаётся читаемым.
    """
    if not text or not needle:
        return text
    lowered = text.lower()
    nlow = needle.lower()
    out = []
    idx = 0
    nlen = len(nlow)
    while True:
        pos = lowered.find(nlow, idx)
        if pos == -1:
            out.append(text[idx:])
            break
        out.append(text[idx:pos])
        out.append(replacement)
        idx = pos + nlen
    return "".join(out)


def sanitize_tone(text: str) -> str:
    """Мягко заменить утверждающие/обвинительные формулировки на нейтральные.

    Никогда не бросает исключение; на пустом входе возвращает пустую строку.
    """
    if not text:
        return ""
    try:
        result = text
        for needle, replacement in _REPLACEMENTS:
            result = _replace_preserve_case(result, needle, replacement)
        return result
    except Exception:
        return text


def get_legal_basis(rule_id: str, rules: Optional[List[Dict]]) -> str:
    """Вернуть юридическое основание (legal_basis) для правила по его id.

    `rules` — список словарей правил (как из rule_engine.load_rules). Если
    правило не найдено или что-то пошло не так — возвращает пустую строку.
    """
    if not rule_id or not rules:
        return ""
    try:
        for rule in rules:
            if not isinstance(rule, dict):
                continue
            if rule.get("id") == rule_id:
                return str(rule.get("legal_basis", "") or "")
    except Exception:
        return ""
    return ""
