"""
Детектор модальных окон (попапов) с формами.

Используется браузерным фетчером (scanner/browser.py) для того, чтобы найти
кнопки/ссылки, открывающие модальные окна с формами («Оставить заявку»,
«Заказать звонок» и т.п.), кликнуть по ним и захватить HTML появившейся формы.

Здесь только лёгкие текстовые эвристики без тяжёлых зависимостей: сам клик и
работа с DOM выполняются в браузерном модуле, а этот модуль лишь отвечает на
вопросы «похоже ли это на триггер модалки?» и «есть ли в HTML признаки формы?».

Важно (юридический тон): модуль не делает выводов о нарушениях — он только
помогает обнаружить формы для последующей нейтральной оценки.
"""
from __future__ import annotations

from typing import List

from scanner import utils

# ---------------------------------------------------------------------------
# Ключевые слова триггеров модальных окон.
# ---------------------------------------------------------------------------
# Тексты кнопок/ссылок, которые обычно открывают модальное окно с формой сбора
# контактных/персональных данных. Порядок не важен — используется поиск вхождения.
MODAL_TRIGGER_KEYWORDS: List[str] = [
    "оставить заявку",
    "записаться",
    "заказать звонок",
    "получить консультацию",
    "обратная связь",
    "связаться",
    "написать",
    "рассчитать",
    "получить предложение",
    "получить прайс",
    "отправить заявку",
    "callback",
    "заявка",
    "консультация",
    "звонок",
    "заказать",
    "прайс",
    "предложение",
    "запись",
]


def is_modal_trigger(text: str) -> bool:
    """True, если текст элемента (кнопки/ссылки) похож на триггер модалки.

    Нормализует текст (нижний регистр, ё->е, схлопывание пробелов) и проверяет
    вхождение любого из ключевых слов MODAL_TRIGGER_KEYWORDS. Никогда не бросает
    исключение — при любой ошибке возвращает False.
    """
    try:
        if not text:
            return False
        return utils.contains_any(text, MODAL_TRIGGER_KEYWORDS)
    except Exception:
        return False


def looks_like_form_html(html: str) -> bool:
    """True, если в HTML-фрагменте есть признаки формы: input/textarea/select.

    Быстрая текстовая проверка (без парсинга DOM), чтобы отсеять модалки без
    полей ввода. Никогда не бросает исключение.
    """
    try:
        if not html:
            return False
        lowered = html.lower()
        return (
            "<input" in lowered
            or "<textarea" in lowered
            or "<select" in lowered
        )
    except Exception:
        return False
